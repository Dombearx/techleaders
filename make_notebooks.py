        "```python",
        "d_z1 = d_a1 * sigmoid_d(z1)",
        "```",
        "",
        "**Steps 7 & 8 — Gradients for W1 and b1 (same pattern as output layer):**",
        "```python",
        "d_W1 = X.T @ d_z1",
        "d_b1 = d_z1.sum(axis=0, keepdims=True)",
        "```",
