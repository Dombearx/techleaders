        "g_z2 = g_a1 @ W2 + b2",
        "g_probs = sigmoid(g_z2).reshape(xx.shape)",
        "",
        "plt.figure(figsize=(5, 5))",
        'plt.contourf(xx, yy, g_probs, levels=50, cmap="RdYlGn", alpha=0.7)',
