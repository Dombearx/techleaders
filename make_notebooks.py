        "```python",
        "d_b2 = d_z2.sum(axis=0, keepdims=True)",
        "```",
        "",
        "### Hidden layer gradients",
        "",
        "**Step 5 — Pass the error signal back through W2 to reach hidden neurons:**",
        "```python",
        "d_a1 = d_z2 @ W2.T",
        "```",
        "",
